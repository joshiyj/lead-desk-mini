export default function SummaryCards({ leads }) {
  const counts = leads.reduce(
    (acc, lead) => {
      acc.total += 1;
      acc[lead.status] = (acc[lead.status] || 0) + 1;
      return acc;
    },
    { total: 0, New: 0, Contacted: 0, Closed: 0 },
  );

  return (
    <div className="summary-grid">
      {CARDS.map(({ label, key, color, icon }) => (
        <div key={key} className={`summary-card summary-card--${color}`}>
          <div className="summary-card-left">
            <div className="summary-icon-box">{icon}</div>
            <div className="summary-info">
              <span className="summary-count">{counts[key] ?? 0}</span>
              <span className="summary-label">{label}</span>
            </div>
          </div>
          <div className="summary-card-chevron">
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
              <polyline points="9 18 15 12 9 6" />
            </svg>
          </div>
        </div>
      ))}
    </div>
  );
}
